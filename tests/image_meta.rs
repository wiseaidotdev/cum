#[test]
fn test_clean_svg_removes_metadata_block() {
    let svg = b"<svg><metadata>AI generated by Claude</metadata><circle/></svg>";
    let clean = clean_image(svg).unwrap();
    let clean_str = std::str::from_utf8(&clean).unwrap();
    assert!(!clean_str.contains("<metadata>"));
    assert!(
        clean_str.contains("<circle/>"),
        "SVG content should be preserved"
    );
}

#[test]
fn test_clean_svg_removes_data_ai_attr() {
    let svg = b"<svg><rect data-ai-provider=\"claude\" /></svg>";
    let clean = clean_image(svg).unwrap();
    let clean_str = std::str::from_utf8(&clean).unwrap();
    assert!(!clean_str.contains("data-ai-provider"));
}

